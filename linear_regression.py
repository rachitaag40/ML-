# Linear Regrassion from scratch

import numpy as np
class Linearregression:
  def __init__(self,learningrate=0.1,epochs=1000):
    self.learningrate=learningrate
    self.epochs = epochs
    self.weights = None
    self.bias = None
    self.losses=[]
  def fit(self,x,y):
    n_samples,n_features=x.shape
    self.weights=np.zeros(n_features)
    self.bias=0
    for i in range(self.epochs):
      y_pred=np.dot(x,self.weights)+self.bias
      loss=(1/n_samples)*np.sum((y-y_pred)**2)
      self.losses.append(loss)
      # calculate the clops wit respect to w and b
      dw=(-2/n_samples)*np.dot(x.T,(y-y_pred))
      db=(-2/n_samples)*np.sum(y-y_pred)

      # weight updation through the gradient descent
      self.weights-=self.learningrate*dw
      self.bias-=self.learningrate*db

    print(self.losses[-1])

  def predict(self,x):
    return np.dot(x,self.weights) + self.bias

x=np.array([[1],[2],[3],[4]])
y=np.array([2,4,6,8])
x_test=np.array([[5]])
model=Linearregression(learningrate=0.1,epochs=1000)
model.fit(x,y)
print(model.predict(x_test))
print("Final weight are ",model.weights)

